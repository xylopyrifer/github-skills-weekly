import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require=createRequire(import.meta.url);
const { chromium }=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.TEST_URL||'http://127.0.0.1:4173';
await mkdir('release/qa',{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
const results=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/#skill/openai%2Fskills');await page.waitForSelector('.migration-notice');
 assert.match(await page.locator('.detail-description').innerText(),/弃用/);
 assert.equal(await page.locator('.migration-notice a').getAttribute('href'),'https://github.com/openai/plugins');
 assert.equal(await page.locator('a.primary-button').getAttribute('href'),'https://github.com/openai/skills');
 assert.ok((await page.locator('.trend-row').count())===5);
 await page.screenshot({path:'release/qa/skills-migration-desktop.png',fullPage:true});
 await page.locator('[data-lang=en]').click();assert.match(await page.locator('.migration-notice').innerText(),/deprecated/);
 await page.reload();await page.waitForSelector('.migration-notice');assert.equal(await page.locator('html').getAttribute('lang'),'en');
 await page.setViewportSize({width:320,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'release/qa/skills-migration-mobile.png',fullPage:true});
 await page.locator('.detail-back').click();await page.waitForSelector('#skill-tag');
 await page.locator('#skill-tag').selectOption('design');
 assert.ok(await page.locator('.search-result').filter({hasText:'Syh1906/openai-compatible-imagegen'}).count());
 await page.locator('#skill-tag').selectOption('finance');
 assert.ok(await page.locator('.search-result').filter({hasText:'xbtlin/ai-berkshire'}).count());
 await page.locator('#skill-tag').selectOption('');
 await page.locator('#skill-query').fill('openai/skills');
 await page.locator('.search-result').filter({hasText:'openai/skills'}).click();await page.waitForSelector('.migration-notice');
 await page.goBack();await page.waitForSelector('#skill-query');
 await page.goForward();await page.waitForSelector('.migration-notice');
 results.push('Bilingual deprecation notice, successor link, original repository identity, history, reload and back/forward navigation');
 results.push('Image generation and financial research appear in their reviewed capability filters');
 results.push('Deprecated detail has no horizontal overflow at 320px');
 const invalid=await browser.newPage();
 await invalid.route('**/assets/data.json',async route=>{const response=await route.fetch();const data=await response.json();data.repositories.find(r=>r.full_name==='openai/skills').editorial.replacement_repository='javascript:alert(1)';await route.fulfill({response,json:data});});
 await invalid.goto(base+'/#skill/openai%2Fskills');await invalid.waitForSelector('.detail-hero');assert.equal(await invalid.locator('.migration-notice').count(),0);
 results.push('Invalid successor identifiers do not become links');
 assert.deepEqual(errors,[]);results.push('No browser runtime errors');
 await writeFile('release/qa/editorial-results.json',JSON.stringify({passed:results.length,results},null,2));console.log(results.join('\n'));
}finally{await browser.close();}
